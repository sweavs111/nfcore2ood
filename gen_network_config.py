#!/usr/bin/env python3

"""Render Hazel network-handling Nextflow configs from site/hazel_network.tsv.

Hazel's compute nodes have no outbound internet, so every nf-core process or
param that downloads at runtime has to be either pointed at a local copy,
moved to the xfer partition, or refused up front. The TSV records that
decision per process/param; this script renders it into the site config
directory (NF2OOD_SITE_CONFIG_DIR) that every generated OOD app's launcher
passes to Nextflow with -c:

    hazel_network.config        process routing/deny rules, every pipeline
    pipeline/<pipeline>.config  precache params for one pipeline (written
                                only for pipelines that have any; <pipeline>
                                is the slug, e.g. mag)

These live outside the nf-core/configs tree on purpose: that tree mirrors
upstream nf-core/configs (whose conf/hazel.config CLI users also fetch), and
pipelines like mag skip pipeline/<name>.config entirely under NXF_OFFLINE.
Loading them with -c works whatever the pipeline's include logic, and the
form's nf-params.json (-params-file) still overrides them.

Rewrites OUTPUT_DIR's pipeline/ subdirectory, so a pipeline whose precache
rows were all removed loses its stale config.

Usage::

    gen_network_config.py TABLE OUTPUT_DIR
"""

from __future__ import annotations

import shutil
import sys
from collections import defaultdict
from pathlib import Path

ACTIONS = ("route", "deny", "precache", "todo", "hide", "hint")
# Rows that only change the generated OOD forms (read by json2ood.py), not
# any Nextflow config.
FORM_ACTIONS = ("hide", "hint")

# Catch-all for download-looking process names the table doesn't list yet.
# Across the 7 pipelines staged when this was written (461 process names) it
# matched exactly the 12 pure-download processes and nothing else.
DOWNLOAD_NAME_RE = r"[A-Z0-9_]*(DOWNLOAD|UPDATE|DATASETGET|DATABASES)[A-Z0-9_]*"

# Sized for the xfer QOS: per user cpu=4, mem=24G, 4 jobs; per account
# (shared by every user in it) cpu=4, mem=48G, 8 jobs. A test-profile
# launcher (2 CPUs, 12G) also runs there, so 1 CPU / 4G lets two routed
# tasks run beside it. Routed tasks only fetch and unpack files, which is
# I/O-bound, so more CPUs or memory wouldn't speed them up. The time cap
# makes an unexpectedly large download fail in bounded time -- a signal to
# pre-cache it -- instead of holding the single xfer node for days.
ROUTE_DIRECTIVES = (
    ("queue", "'xfer'"),
    ("clusterOptions", "'--qos=xfer'"),
    ("cpus", "1"),
    ("memory", "4.GB"),
    ("time", "4.h"),
)


def parse_table(table_path: Path) -> list[dict[str, str]]:
    rows = []
    for lineno, line in enumerate(table_path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 6:
            raise ValueError(f"{table_path}:{lineno}: expected 6 tab-separated fields, got {len(fields)}")
        row = dict(zip(("pipeline", "process", "action", "param", "value", "note"), fields))
        if row["action"] not in ACTIONS:
            raise ValueError(f"{table_path}:{lineno}: unknown action {row['action']!r}")
        if row["action"] in ("route", "deny") and (row["pipeline"] != "*" or row["process"] == "-"):
            raise ValueError(f"{table_path}:{lineno}: {row['action']} rows need pipeline * and a process name")
        if row["action"] in ("precache", "hint") and (row["pipeline"] == "*" or row["param"] == "-" or row["value"] == "-"):
            raise ValueError(f"{table_path}:{lineno}: {row['action']} rows need a pipeline, param and value")
        if row["action"] == "hide" and row["param"] == "-":
            raise ValueError(f"{table_path}:{lineno}: hide rows need a param")
        row["lineno"] = str(lineno)
        rows.append(row)
    return rows


def groovy_str(text: str) -> str:
    # Single-quoted Groovy string: no interpolation, so only \ and ' need escaping.
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def name_selector(pattern: str, exclude: list[str] | None = None) -> str:
    # withName is matched against both the simple and the fully qualified
    # (WORKFLOW:SUBWORKFLOW:NAME) process name, so allow either form.
    lookahead = f"(?!({'|'.join(exclude)})$)" if exclude else ""
    return groovy_str(f"(.*:)?{lookahead}({pattern})")


def render_network_config(rows: list[dict[str, str]]) -> str:
    routes = [r for r in rows if r["action"] == "route"]
    denies = [r for r in rows if r["action"] == "deny"]
    out = [
        "// Generated by gen_network_config.py from site/hazel_network.tsv -- edit the TSV, not this file.",
        "//",
        "// Routes runtime-download processes to the xfer partition (the one Hazel",
        "// partition with outbound internet) and refuses ones too large to fetch per run.",
        "",
        "process {",
        "    // route (from the table):",
    ]
    out += [f"    //   {r['process']}: {r['note']}" for r in routes]
    out += [
        "    // plus a catch-all for unlisted download-looking names, so a new pipeline",
        "    // version runs slowly on xfer instead of failing on compute until classified.",
        "    // Denied names are excluded so they fail fast on compute with their message",
        "    // rather than queueing on the single xfer node first.",
        f"    withName: {name_selector('|'.join([r['process'] for r in routes] + [DOWNLOAD_NAME_RE]), [r['process'] for r in denies])} {{",
    ]
    width = max(len(k) for k, _ in ROUTE_DIRECTIVES)
    out += [f"        {k.ljust(width)} = {v}" for k, v in ROUTE_DIRECTIVES]
    out.append("    }")
    for r in denies:
        message = (
            f"{r['process']} is disabled on Hazel: {r['note']}. "
            f"Ask BRC (ncstate_brc@ncsu.edu) for a local copy to pass as --{r['param']}."
        )
        out += [
            "",
            f"    // deny: {r['note']}",
            f"    withName: {name_selector(r['process'])} {{",
            # beforeScript runs inside the task ahead of the command, so the
            # task fails at once with this message instead of downloading.
            f"        beforeScript = {groovy_str(f'echo {shell_quote(message)} >&2; exit 1')}",
            "    }",
        ]
    out.append("}")
    return "\n".join(out) + "\n"


def shell_quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$").replace("`", "\\`") + '"'


def render_pipeline_config(pipeline: str, rows: list[dict[str, str]]) -> str:
    precache = [r for r in rows if r["action"] == "precache"]
    todo = [r for r in rows if r["action"] == "todo"]
    out = [
        "// Generated by gen_network_config.py from site/hazel_network.tsv -- edit the TSV, not this file.",
        f"// nf-core/{pipeline}: local copies of data the pipeline would otherwise download at runtime.",
        "// Loaded by the OOD launcher with -c, except under the built-in test profile.",
        "",
    ]
    if precache:
        width = max(len(r["param"]) for r in precache)
        out.append("params {")
        for r in precache:
            out.append(f"    // {r['note']}")
            value = "null" if r["value"] == "null" else groovy_str(r["value"])
            out.append(f"    {r['param'].ljust(width)} = {value}")
        out.append("}")
    for r in todo:
        out.append(f"// TODO {r['param']}: {r['note']}")
    return "\n".join(out) + "\n"


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_network_config.py TABLE OUTPUT_DIR\n")
        return 1

    table_path = Path(sys.argv[1])
    output_dir = Path(sys.argv[2])
    rows = parse_table(table_path)

    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "hazel_network.config").write_text(render_network_config(rows), encoding="utf-8")

    by_pipeline: dict[str, list[dict[str, str]]] = defaultdict(list)
    for r in rows:
        if r["pipeline"] != "*" and r["action"] not in FORM_ACTIONS:
            by_pipeline[r["pipeline"]].append(r)

    for r in rows:
        # Precache paths are read on the compute node at run time; a typo here
        # would only surface mid-pipeline, so flag it now.
        if r["action"] in ("precache", "hint") and r["value"] != "null" and not Path(r["value"]).exists():
            sys.stderr.write(f"gen_network_config: warning: line {r['lineno']}: {r['value']} does not exist\n")

    pipeline_dir = output_dir / "pipeline"
    if pipeline_dir.exists():
        shutil.rmtree(pipeline_dir)
    written = []
    for pipeline, pipeline_rows in sorted(by_pipeline.items()):
        if not any(r["action"] == "precache" for r in pipeline_rows):
            # TODO-only: nothing for Nextflow to load. The table keeps the note.
            continue
        pipeline_dir.mkdir(exist_ok=True)
        path = pipeline_dir / f"{pipeline}.config"
        path.write_text(render_pipeline_config(pipeline, pipeline_rows), encoding="utf-8")
        written.append(pipeline)

    sys.stderr.write(
        f"gen_network_config: wrote {output_dir}/hazel_network.config"
        f" and pipeline configs for: {', '.join(written) or '(none)'}\n"
    )
    for r in rows:
        if r["action"] == "todo":
            sys.stderr.write(f"gen_network_config: todo {r['pipeline']} {r['param']}: {r['note']}\n")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:  # pragma: no cover - CLI error path
        sys.stderr.write(f"gen_network_config: error: {exc}\n")
        raise SystemExit(1)
